export function getSpeciesExplorerCopy(language: Language) {
  return speciesExplorerCopy[language];
}

export function formatExplorerText(template: string, values: Record<string, number | string>) {
  return template.replace(/\{([^}]+)\}/g, (match, key: string) => String(values[key] ?? match));
}
